/**
 * ทะเบียนผู้มารับบริการ — visit registry rows.
 *
 * Fields mirror the dataset behind PatientVisitListFrameUnit.dfm
 * (VisitListCDS.CommandText: ovst + vn_stat + opdscreen + patient + …).
 * Each property maps 1:1 to a DFM grid column / SQL alias.
 */
export interface VisitRegistryRow {
  vn: string // visit number
  rowNo: number // row_no — ลำดับ
  hospitalDepartmentName: string // hospital_department_name — สาขาที่ส่งตรวจ
  vstdate: string // vstdate — วันที่ (ISO yyyy-MM-dd)
  vsttime: string // vsttime — เวลา (HH:mm)
  oqueue: string // oqueue — Queue
  cid: string // cid — CID
  hn: string // hn — HN
  ptname: string // ptname — ชื่อผู้รับบริการ
  photo?: string
  visitTypeName: string // visit_type_name — เวลาทำการ
  pttypeCheckStatusName: string // pttype_check_status_name — การตรวจสอบสิทธิ
  ovstistName: string // ovstist_name — ประเภทการมา
  ptPriorityName: string // pt_priority_name — ความเร่งด่วน
  ptWalkName: string // pt_walk_name — ประเภท
  pttypeName: string // pttype_name — สิทธิการรักษา
  pttypeno: string // pttypeno — เลขที่สิทธิ
  ageY: number // age_y — อายุ (ปี)
  ageM: number // age_m — อายุ (เดือน)
  ageD: number // age_d — อายุ (วัน)
  cc: string // cc — อาการสำคัญ
  doctorListText: string // doctor_list_text — แพทย์ผู้ตรวจ
  countInDay: number // count_in_day — มาครั้งที่ (ในวัน)
  countInMonth: number // count_in_month — มาครั้งที่ (ในเดือน)
  countInYear: number // count_in_year — มาครั้งที่ (ในปี)
  pdx: string // pdx — Primary Dx.
  pdxName: string // pdx_name — ผลการวินิจฉัย
  dxTextList: string // dx_text_list — Diag Text
  registerDepartmentName: string // register_department_name — ส่งตรวจที่ห้อง
  spcltyName: string // spclty_name — แผนก
  subSpcltyName: string // sub_spclty_name — สาขา
  departmentName: string // department_name — จุดรับบริการปัจจุบัน
  ostName: string // ost_name — สถานะภาพ
  ptSubtypeName: string // pt_subtype_name — ประเภทคนไข้
  mainDepartmentName: string // main_department_name — จุดรับบริการแรก
  bps: number // bps — BPs
  bpd: number // bpd — BPd
  temperature: number // temperature — อุณหภูมิ
  bw: number // bw — น้ำหนัก
  an: string // an — AN (Admit)
  staffName: string // staff_name — เจ้าหน้าที่ส่งตรวจ
  income: number // income — ค่าใช้จ่ายทั้งหมด
  paidMoney: number // paid_money — ต้องชำระเงิน
  rcptMoney: number // rcpt_money — ออกใบเสร็จรับเงิน
  authCode: string // auth_code — Auth code (สปสช.)
  nhsoFeeScheduleListText: string // nhso_fee_schedule_list_text — NHSO Fee Schedule
}

